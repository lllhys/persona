/**
 * Kotlin drives the real Rust JNI projection. The Apple-derived expectations remain in the shared corpus and its
 * checked-in iOS overlay; no expected turn is generated by Rust and no lines fixture or Swift replay is changed.
 */
class TurnBindingFixtureTest {
    private val root: File = generateSequence(File(".").canonicalFile) { it.parentFile }
        .firstOrNull { File(it, ".git").exists() && File(it, "android").isDirectory }
        ?: error("Cannot locate the repository")
    private val fixtures = root.resolve("spec/fixtures/lines")
    private val overlayPath = fixtures.resolve("ios/differences.json")
    private val overlay = Json.parseToJsonElement(overlayPath.readText()).jsonObject
    private val wake = overlay.getValue("turn_wake_state").jsonObject
    private val patchCases = overlay.getValue("cases").jsonArray.map { it.jsonObject }
    private val replayed = mutableSetOf<String>()
    private val emptyOnlyCases = setOf("empty_session", "single_interaction_in_footer", "multiple_interactions_in_footer")

    private fun currentAppleExpected(case: JsonObject, applyCasePatch: Boolean): JsonArray {
        val name = case.getValue("name").jsonPrimitive.content
        val wakeDrop = wake.getValue("drop").jsonPrimitive.content
        val wakeSet = wake.getValue("set").jsonPrimitive.content
        val turns = case.getValue("expected").jsonObject.getValue("turns").jsonArray.map { element ->
            val turn = element.jsonObject.toMutableMap()
            assertTrue("$name: stale wake drop", turn.remove(wakeDrop) != null)
            assertFalse("$name: stale wake set", turn.containsKey(wakeSet))
            val pending = wake.getValue("pending").jsonArray.any { reference ->
                reference.jsonObject.getValue("case").jsonPrimitive.content == name &&
                    reference.jsonObject.getValue("turn").jsonPrimitive.content == turn.getValue("id").jsonPrimitive.content
            }
            turn[wakeSet] = kotlinx.serialization.json.JsonPrimitive(pending)
            JsonObject(turn)
        }
        val expected = case.getValue("expected").jsonObject.toMutableMap()
        expected["turns"] = JsonArray(turns)
        if (applyCasePatch) {
            for (entry in patchCases.filter { it.getValue("name").jsonPrimitive.content == name }) {
                assertTrue(
                    "$name: unexpected overlay key",
                    entry.keys.all { it in setOf("name", "why", "source", "replace", "turn_fields") },
                )
                assertTrue("$name: missing overlay rationale", entry.getValue("why").jsonPrimitive.content.isNotEmpty())
                assertTrue("$name: missing overlay sources", entry.getValue("source").jsonArray.isNotEmpty())
                for ((key, replacement) in entry["replace"]?.jsonObject.orEmpty()) {
                    assertNotEquals("$name: stale replace $key", expected[key], replacement)
                    expected[key] = replacement
                }
                for ((id, fields) in entry["turn_fields"]?.jsonObject.orEmpty()) {
                    val patchedTurns = expected.getValue("turns").jsonArray.map { element ->
                        val turn = element.jsonObject.toMutableMap()
                        if (turn.getValue("id").jsonPrimitive.content == id) {
                            for ((key, replacement) in fields.jsonObject) {
                                assertNotEquals("$name/$id: stale field $key", turn[key], replacement)
                                turn[key] = replacement
                            }
                        }
                        JsonObject(turn)
                    }
                    assertEquals(
                        "$name/$id: overlay must name exactly one turn",
                        1,
                        patchedTurns.count { it.getValue("id").jsonPrimitive.content == id },
                    )
                    expected["turns"] = JsonArray(patchedTurns)
                }
            }
        }
        return expected.getValue("turns").jsonArray
    }

    private fun replay(case: JsonObject): JsonElement {
        val name = case.getValue("name").jsonPrimitive.content
        val output = NativeBridge.projectTurns(case.getValue("input").jsonObject.toString())
        assertTrue("$name: JNI returned no projection", output.isNotEmpty())
        return Json.parseToJsonElement(output)
    }

    private fun assertTurnsEqual(case: JsonObject, expected: JsonElement, actual: JsonElement) {
        assertEquals(case.getValue("name").jsonPrimitive.content, expected, actual)
    }

    @Test fun replayEveryStaticTurnThroughJni() {
        assertTrue("the checked-in Apple overlay is required", overlayPath.isFile)
        val files = requireNotNull(fixtures.listFiles { file -> file.isFile && file.extension == "json" })
            .sortedBy { it.name }
        assertEquals("the lines file set is the manifest boundary", 9, files.size)
        val allNames = mutableSetOf<String>()
        val allTurns = mutableSetOf<Pair<String, String>>()
        val patchNames = mutableSetOf<String>()
        for (entry in patchCases) {
            assertTrue("duplicate overlay case", patchNames.add(entry.getValue("name").jsonPrimitive.content))
        }
        for (file in files) {
            val document = Json.parseToJsonElement(file.readText()).jsonObject
            for (element in document.getValue("cases").jsonArray) {
                val case = element.jsonObject
                val name = case.getValue("name").jsonPrimitive.content
                assertTrue("duplicate corpus case $name", allNames.add(name))
                val expected = case.getValue("expected").jsonObject
                val checkpoints = expected["checkpoints"]?.jsonArray ?: JsonArray(listOf(expected))
                for (state in checkpoints) {
                    for (turn in state.jsonObject["turns"]?.jsonArray.orEmpty()) {
                        allTurns.add(name to turn.jsonObject.getValue("id").jsonPrimitive.content)
                    }
                }
                if (expected.containsKey("checkpoints") || case.getValue("input").jsonObject.containsKey("operations")) continue
                val actual = replay(case)
                assertTurnsEqual(case, currentAppleExpected(case, applyCasePatch = true), actual)
                if (name in patchNames) {
                    assertNotEquals(
                        "$name: unnecessary overlay case entry",
                        currentAppleExpected(case, applyCasePatch = false),
                        actual,
                    )
                }
                assertTrue("duplicate replayed case $name", replayed.add(name))
            }
        }
        assertTrue("overlay names a nonexistent case", allNames.containsAll(patchNames))
        val pendingReferences = mutableSetOf<Pair<String, String>>()
        for (reference in wake.getValue("pending").jsonArray.map { it.jsonObject }) {
            val key = reference.getValue("case").jsonPrimitive.content to
                reference.getValue("turn").jsonPrimitive.content
            assertTrue("duplicate pending overlay reference", pendingReferences.add(key))
            assertTrue("overlay names a nonexistent pending turn $key", key in allTurns)
        }
        assertEquals("only the four operation cases are excluded", 61, allNames.size)
        assertEquals("exact static turn manifest", expectedStaticCases, replayed)
        val turnCount = replayed.sumOf { name ->
            val expected = currentAppleExpected(fixtureCase(name), applyCasePatch = true)
            if (name in emptyOnlyCases) {
                assertTrue("$name compares an empty turn array, not layout", expected.isEmpty())
                0
            } else {
                assertTrue("$name has turn-grouping coverage", expected.isNotEmpty())
                expected.size
            }
        }
        assertEquals("three empty-array cases do not count as layout coverage", 73, turnCount)
        println("JNI turn host replay: ${replayed.size} cases; 54 with 73 complete turn objects; 3 empty arrays")
    }

    @Test fun boundaryRejectsMalformedInputAndTheComparisonRejectsAWrongExpectation() {
        assertEquals("", NativeBridge.projectTurns("{\"invalid\":true}"))
        assertEquals("", NativeBridge.projectTurns("not JSON"))
        val case = fixtureCase("plain_exchange")
        val actual = replay(case)
        val wrong = buildJsonObject {
            put("turns", JsonArray(listOf(JsonObject(emptyMap()))))
        }.getValue("turns")
        assertNotEquals("the negative fixture must actually differ", wrong, actual)
        val failure = assertThrows("the complete-turn comparison accepted a wrong expectation", AssertionError::class.java) {
            assertTurnsEqual(case, wrong, actual)
        }
        assertTrue(failure.message.orEmpty().contains("plain_exchange"))
    }

    private fun fixtureCase(name: String): JsonObject =
        requireNotNull(fixtures.listFiles { file -> file.isFile && file.extension == "json" })
            .asSequence()
            .flatMap { file ->
                Json.parseToJsonElement(file.readText()).jsonObject.getValue("cases").jsonArray
            }
            .map { it.jsonObject }
            .first { it.getValue("name").jsonPrimitive.content == name }

    private companion object {
        val expectedStaticCases = setOf(
            "absorbed_user_images", "background_running_badge", "closed_work_identity",
            "compaction_stays_inside_work", "empty_session", "empty_thinking_between_tools_is_retained",
            "failed_tool_counts_known_failure", "fold_counts_tools_and_thoughts",
            "frozen_snapshot_excludes_newer_items", "frozen_uses_numeric_block_order", "interrupt_is_trailing_notice",
            "last_result_for_call_wins", "late_result_attaches_to_original_call", "live_answer_after_wake",
            "live_empty_work", "live_queued_message_keeps_position", "live_reply_stays_after_work",
            "live_tail_runs_behind_chip", "long_answer_after_wake", "menu_owner_per_message",
            "missing_start_time_hides_duration", "missing_start_time_uses_first_step", "missing_tool_result_is_running",
            "monitor_event_uses_first_detail_line", "multiple_interactions_in_footer",
            "multiple_wakes_pick_latest_answer", "notification_without_wake",
            "older_page_stays_visible_during_freeze", "only_last_reply_in_each_wake_is_candidate",
            "open_queued_messages_work", "open_work_identity", "orphan_assistant", "orphan_tool_result_is_not_a_row",
            "orphan_wake_opens_with_notice", "ordinary_user_starts_next_turn", "photos_after_wake_stay_with_message",
            "plain_exchange", "queued_without_existing_turn", "recap_separates_turns", "regular_user_images",
            "short_reply_after_wake_is_the_answer", "single_interaction_in_footer", "standalone_empty_thinking_hidden",
            "task_notices_find_calls", "task_status_outcomes", "task_title_containing_interrupt_is_not_interrupt",
            "task_without_loaded_call_uses_title", "thinking_before_between_after_tools",
            "thinking_narration_preserved", "three_users_apart_without_steps", "timed_work_ends_at_answer",
            "tool_images_belong_to_call", "trailing_tool_after_answer", "unknown_item_is_ignored",
            "wake_after_recap_reopens_turn", "wake_without_any_reply", "finished_queued_messages_apart",
        )
    }
}
